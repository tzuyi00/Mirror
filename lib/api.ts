// ===== Profile API =====

import type { Memory, ProfileSection } from "@/components/profile/types";

/**
 * API Response wrapper for profile endpoints
 */
export interface ProfileApiResponse<T = any> {
  status: number;
  message: string;
  apiId: string;
  version: string;
  requestId: string;
  timestamp: string;
  lang: string;
  data?: T;
  error?: {
    code: string;
    details?: any;
  };
}

/**
 * Profile data structure returned from backend
 */
export interface ProfileData {
  userId: string;
  name: string;
  title: string;
  bio: string;
  sections: ProfileSection[];
  memories: Memory[];
}

/**
 * User model data (from User table only)
 */
export interface UserData {
  userId: string;
  name: string;
  title: string;
  bio: string;
}

/**
 * Profile view response structure (BFF endpoint)
 */
interface ProfileViewResponse {
  profileView: {
    userId: string;
    name: string;
    title: string;
    bio: string;
    sections: ProfileSection[];
    memories?: Memory[];
  };
}

/**
 * Get User model data only (from User table)
 * 
 * @param userId - The user ID to fetch
 * @returns Promise with user data
 */
export async function getUser(userId: string): Promise<UserData> {
  const response = await http<ProfileApiResponse<{ user: UserData }>>(
    `/api/users/${encodeURIComponent(userId)}`,
    { method: "GET" }
  );

  if (!response.data?.user) {
    throw new Error("No user data returned from API");
  }

  return response.data.user;
}

/**
 * Get complete profile view including user, sections, and optionally memories
 * This is a BFF (Backend-for-Frontend) endpoint
 * 
 * @param userId - The user ID to fetch profile for
 * @param includeMemories - Whether to include memories in the response
 * @returns Promise with complete profile data
 */
export async function getProfileView(userId: string, includeMemories: boolean = true): Promise<ProfileData> {
  const queryString = includeMemories ? '?include=memories' : '';
  const response = await http<ProfileApiResponse<ProfileViewResponse>>(
    `/api/profile-views/${encodeURIComponent(userId)}${queryString}`,
    { method: "GET" }
  );

  if (!response.data?.profileView) {
    throw new Error("No profile data returned from API");
  }

  const { profileView } = response.data;
  
  return {
    userId: profileView.userId,
    name: profileView.name,
    title: profileView.title,
    bio: profileView.bio,
    sections: profileView.sections,
    memories: profileView.memories || []
  };
}

/**
 * Get a specific profile section by section ID
 * 
 * @param userId - The user ID
 * @param sectionId - The section ID to fetch
 * @returns Promise with section data and related memories
 */
export async function getProfileSection(
  userId: string,
  sectionId: string
): Promise<{ section: ProfileSection; memories: Memory[] }> {
  const response = await http<ProfileApiResponse<{ section: ProfileSection; memories: Memory[] }>>(
    `/api/profile/${encodeURIComponent(userId)}/sections/${encodeURIComponent(sectionId)}`,
    { method: "GET" }
  );

  if (!response.data) {
    throw new Error("No section data returned from API");
  }

  return response.data;
}

/**
 * Profile generation result from backend
 */
export interface ProfileGenerationResult {
  userId: string;
  generatedAt: string;
  model: string;
  sectionsCount: number;
  latency_ms?: number;
}

/**
 * Generate user profile using AI and save to database
 * This triggers the complete flow:
 * 1. AI generates profile data
 * 2. Backend saves to database
 * 3. Returns the generated userId
 * 
 * @param userId - Optional: If provided, updates existing user profile; otherwise creates new user
 * @returns Promise with generation result including userId and metadata
 */
export async function generateProfile(userId?: string): Promise<ProfileGenerationResult> {
  console.log('[Frontend API] Generating profile...', userId ? `for userId: ${userId}` : 'for new user');
  
  const response = await http<ProfileApiResponse<ProfileGenerationResult>>(
    '/api/profile/generate',
    {
      method: 'POST',
      body: JSON.stringify({ userId: userId || undefined })
    }
  );

  if (!response.data) {
    throw new Error('No generation result returned from API');
  }

  return response.data;
}

