// ===== Auth API =====

/**
 * User data returned from auth endpoints
 */
export interface AuthUser {
  id: string;
  name: string | null;
  email: string | null;
  image?: string | null;
}

/**
 * Auth API response wrapper
 */
interface AuthResponse<T> {
  message: string;
  user?: T;
  error?: string;
}

/**
 * Sign up a new user
 * 
 * @param email - User email
 * @param password - User password (plain text, will be hashed on backend)
 * @param name - User name (optional)
 * @returns Promise with created user data
 */
export async function signUp(
  email: string,
  password: string,
  name?: string
): Promise<AuthUser> {
  const response = await http<AuthResponse<AuthUser>>(
    '/api/auth/signup',
    {
      method: 'POST',
      body: JSON.stringify({ email, password, name })
    }
  );

  if (!response.user) {
    throw new Error(response.error || 'Failed to create account');
  }

  return response.user;
}

/**
 * Verify user credentials (for NextAuth)
 * 
 * @param email - User email
 * @param password - User password
 * @returns Promise with user data if credentials are valid
 */
export async function verifyCredentials(
  email: string,
  password: string
): Promise<AuthUser> {
  const response = await http<AuthResponse<AuthUser>>(
    '/api/auth/verify-credentials',
    {
      method: 'POST',
      body: JSON.stringify({ email, password })
    }
  );

  if (!response.user) {
    throw new Error(response.error || 'Invalid credentials');
  }

  return response.user;
}

