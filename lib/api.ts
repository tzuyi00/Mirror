/**
 * Memory creation request body
 */
export interface CreateMemoryRequest {
  userId: string;
  type: 'user' | 'ai';
  content: string;
  source: string;
  categories: string[];  // Array of category tags
  sectionIds?: string[];
}

/**
 * Memory update request body
 */
export interface UpdateMemoryRequest {
  content?: string;
  source?: string;
  categories?: string[];  // Array of category tags
}

/**
 * Create a new memory
 * 
 * @param request - Memory creation data
 * @returns Promise with created memory
 */
export async function createMemory(request: CreateMemoryRequest): Promise<Memory> {
  console.log('[Frontend API] Creating memory...', request);
  
  const response = await http<ProfileApiResponse<{ memory: Memory }>>(
    '/api/memories',
    {
      method: 'POST',
      body: JSON.stringify(request)
    }
  );

  if (!response.data?.memory) {
    throw new Error('No memory data returned from API');
  }

  return response.data.memory;
}

/**
 * Update an existing memory
 * 
 * @param memoryId - The memory ID to update
 * @param request - Memory update data
 * @returns Promise with updated memory
 */
export async function updateMemory(
  memoryId: string,
  request: UpdateMemoryRequest
): Promise<Memory> {
  console.log('[Frontend API] Updating memory...', memoryId, request);
  
  const response = await http<ProfileApiResponse<{ memory: Memory }>>(
    `/api/memories/${encodeURIComponent(memoryId)}`,
    {
      method: 'PATCH',
      body: JSON.stringify(request)
    }
  );

  if (!response.data?.memory) {
    throw new Error('No memory data returned from API');
  }

  return response.data.memory;
}

/**
 * Delete a memory (supports soft and hard delete modes)
 * 
 * @param memoryId - The memory ID to delete
 * @param mode - Delete mode: 'soft' (add deleted tag) or 'hard' (actually delete from DB)
 * @returns Promise with deleted memory (soft mode) or empty object (hard mode)
 */
export async function deleteMemory(
  memoryId: string,
  mode: 'soft' | 'hard' = 'soft'
): Promise<Memory | null> {
  console.log('[Frontend API] Deleting memory...', memoryId, `mode: ${mode}`);
  
  const response = await http<ProfileApiResponse<{ memory?: Memory }>>(
    `/api/memories/${encodeURIComponent(memoryId)}?mode=${mode}`,
    {
      method: 'DELETE'
    }
  );

  // Hard delete returns empty data, soft delete returns updated memory
  return response.data?.memory || null;
}

