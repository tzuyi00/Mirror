const BASE =
  process.env.NEXT_PUBLIC_SERVER_BASE_URL?.replace(/\/$/, "") ||
  "http://localhost:3001";

export type Role = "user" | "ai" | "system";
export interface Message {
  id?: string;
  createdAt?: string;
  role: Role;
  data?: unknown;
  threadId?: string;
}
export interface AIError {
  code: string;
  message: string;
  retryable?: boolean;
  details?: unknown;
}
export interface AIMeta {
  threadId: string;
  messageId?: string;
  createdAt: string;
  model?: string;
  latency_ms?: number;
}
export interface AIContinuation {
  type: "none" | "stream" | "paginate" | "followup_required";
  cursor?: string;
  hint?: string;
}

export interface ChatResponse {
  ok: boolean;
  reply?: string;
  suggestions?: string[];
  modules: unknown[];
  error?: AIError;
  meta: AIMeta;
  continuation?: AIContinuation;
}

async function http<T>(path: string, init?: RequestInit): Promise<T> {
  const res = await fetch(`${BASE}${path}`, {
    ...init,
    headers: {
      "Content-Type": "application/json",
      "ngrok-skip-browser-warning": "true",  // Skip ngrok warning page
      ...(init?.headers || {}),
    },
  });
  if (!res.ok) {
    let detail: unknown;
    try {
      detail = await res.json();
    } catch {}
    throw new Error(
      `HTTP ${res.status} ${res.statusText}` +
        (detail ? ` - ${JSON.stringify(detail)}` : "")
    );
  }
  return (await res.json()) as T;
}

